// Optional, isolated browser smoke. Every generated decision is SYNTHETIC.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { prepareRadialComparison, writeRadialComparison } from '../tools/compare-radial-revision.mjs';
const { chromium } = createRequire(import.meta.url)('playwright');
const base = process.env.REPAIR_TEST_URL || 'http://127.0.0.1:8876';
const output = path.resolve('research/generated/qa-radial-comparison');
const archive = JSON.parse(await fs.readFile('research/generated/radial-loop-v1/qa/synthetic-browser-complete.json', 'utf8'));
assert.equal(archive.protocol.synthetic, true);
const revision = JSON.parse(JSON.stringify(archive.source.rules));
revision.revision = 'synthetic-browser-v2';
revision.basedOn = archive.candidates.filter(c => c.role === 'study').map(c => c.id);
revision.hypothesis = 'SYNTHETIC browser verification: shift the shared center four pixels. Not a design recommendation.';
revision.ranges.centerY = revision.ranges.centerY.map(x => x + 4);
await fs.mkdir(output, { recursive: true });
await fs.writeFile(path.join(output, 'synthetic-rules.json'), JSON.stringify(revision));
await writeRadialComparison(prepareRadialComparison(archive, revision), output);
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const context = await browser.newContext({ viewport: { width: 1400, height: 1050 }, acceptDownloads: true });
const errors = [];
context.on('page', page => page.on('pageerror', e => errors.push(e.message)));
await context.route('**/*', route => route.request().url().startsWith(base) || /^(data:|blob:)/.test(route.request().url()) ? route.continue() : route.abort());
try {
  const page = await context.newPage();
  await page.goto(`${base}/research/generated/qa-radial-comparison/`);
  assert.equal(await page.locator('section').count(), 6);
  assert.equal(await page.locator('section svg').count(), 12);
  const first = page.locator('section').first();
  await first.locator('[data-key=preference]').selectOption('both-bad');
  await first.locator('[data-key=note]').fill('SYNTHETIC transport test, not author feedback.');
  await page.reload();
  assert.equal(await first.locator('[data-key=preference]').inputValue(), 'both-bad');
  await page.screenshot({ path: path.join(output, 'review.png') });
  const playing = context.waitForEvent('page');
  await first.getByRole('link', { name: 'Играть A' }).click();
  const player = await playing;
  await player.waitForFunction(() => document.documentElement.classList.contains('player-ready'));
  await player.locator('#gameCanvas').waitFor({ state: 'visible' });
  assert.equal(await player.evaluate(() => window.__PEGGLE_API_BASE__), '/api');
  await player.screenshot({ path: path.join(output, 'native-player.png') });
  const downloading = page.waitForEvent('download'); await page.locator('#export').click();
  const saved = path.join(output, 'synthetic-review.json'); await (await downloading).saveAs(saved);
  const result = JSON.parse(await fs.readFile(saved, 'utf8'));
  assert.equal(result.decisions.length, 6); assert.equal(result.decisions[0].preference, 'both-bad');
  assert.equal(result.decisions[1].preference, '', 'Keep unfinished rows; never fabricate answers');
  assert.deepEqual(errors, []);
  console.log('Comparison browser passed: all six pairs -> autosave/reload -> native hash player -> complete six-row export with missing answers retained.');
} finally { await browser.close(); }
